import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { walkFiles } from "./lib/files.mjs";
import { assertValidWorksSvg, extractSvg } from "./lib/svg-contract.mjs";

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const sourceRoot = path.join(repositoryRoot, "src", "icons");
const outputPath = path.join(
  repositoryRoot,
  "src",
  "generated",
  "custom-icons.ts",
);
const checking = process.argv.includes("--check");

function normaliseBody(body) {
  return body.replace(/>\s+</g, "><").replace(/\s+/g, " ").trim();
}

export async function renderCustomIconModule() {
  const files = await walkFiles(sourceRoot, (file) => file.endsWith(".svg"));
  const entries = [];

  for (const file of files) {
    const source = await readFile(file, "utf8");
    const relative = path.relative(sourceRoot, file).split(path.sep).join("/");
    assertValidWorksSvg(source, relative);
    const { body } = extractSvg(source);
    const key = relative.slice(0, -".svg".length);
    entries.push({
      key,
      body: normaliseBody(body),
    });
  }

  const lines = [
    "// Generated by scripts/generate-custom-icons.mjs. Do not edit by hand.",
    'import type { ResolvedCustomIcon } from "../catalog/types.js";',
    "",
    "export const customIconData = Object.freeze({",
  ];

  for (const entry of entries) {
    lines.push(
      `  ${JSON.stringify(entry.key)}: { id: ${JSON.stringify(entry.key)}, viewBox: "0 0 24 24", body: ${JSON.stringify(entry.body)} },`,
    );
  }

  lines.push(
    "}) satisfies Readonly<",
    "  Record<string, ResolvedCustomIcon>",
    ">;",
    "",
  );

  return lines.join("\n");
}

const rendered = await renderCustomIconModule();
if (checking) {
  const existing = await readFile(outputPath, "utf8");
  if (existing !== rendered) {
    console.error(
      "src/generated/custom-icons.ts is stale. Run npm run generate.",
    );
    process.exitCode = 1;
  } else {
    console.log("Custom icon data is current.");
  }
} else {
  await writeFile(outputPath, rendered, "utf8");
  console.log(`Generated ${path.relative(repositoryRoot, outputPath)}.`);
}
